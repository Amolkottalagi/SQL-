"""One-command database setup for a fresh MySQL/MariaDB server.

    python -m backend.setup_db                       # asks for the MySQL admin password and an app admin user
    python -m backend.setup_db --admin-password ...  # non-interactive (see --help)

It will
  1. create the app database (app_db) from sql/001_schema.sql and sql/002_evaluation.sql,
  2. create the demo database the AI answers questions about (shop_db) and its SELECT-only account,
  3. create a least-privilege account for the app itself,
  4. write a .env file with generated passwords (never overwrites an existing .env),
  5. seed plans, the default prompt template, few-shot examples and test questions,
  6. optionally create an admin user for the web app.

It is safe to run again: existing tables are left alone. Use --reset to wipe app_db and start over.
"""
import argparse
import getpass
import os
import re
import secrets
import sys
from pathlib import Path

import mysql.connector

ROOT = Path(__file__).resolve().parent.parent
SQL_DIR = ROOT / "sql"
ENV_PATH = ROOT / ".env"
APP_USER, READER_USER = "sqlllm_app", "llm_reader"
PLACEHOLDER_APP_PW, PLACEHOLDER_READER_PW = "app_pw_change_me", "reader_pw_change_me"


def split_statements(text: str) -> list[str]:
    """Split a .sql file into statements. Good enough for our own files: it assumes no '--' or ';'
    inside string literals and no DELIMITER blocks."""
    text = re.sub(r"--[^\n]*", "", text)
    return [s.strip() for s in text.split(";") if s.strip()]


def run_sql_file(conn, path: Path, replacements: dict[str, str] | None = None) -> None:
    text = path.read_text(encoding="utf-8")
    for old, new in (replacements or {}).items():
        text = text.replace(old, new)
    cur = conn.cursor()
    for stmt in split_statements(text):
        cur.execute(stmt)
    cur.close()


def _read_env_file() -> dict:
    values = {}
    if ENV_PATH.is_file():
        for line in ENV_PATH.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                values[k.strip()] = v.strip().strip("'\"")
    return values


def _scalar(conn, sql, args=None):
    cur = conn.cursor()
    cur.execute(sql, args)
    row = cur.fetchone()
    cur.close()
    return row[0] if row else None


def write_env(host: str, port: int, app_pw: str, reader_pw: str) -> bool:
    if ENV_PATH.exists():
        return False
    ENV_PATH.write_text(
        "# Generated by `python -m backend.setup_db`. Keep this file private (it is in .gitignore).\n"
        f"DB_HOST={host}\nDB_PORT={port}\nDB_USER={APP_USER}\nDB_PASSWORD={app_pw}\nDB_NAME=app_db\n\n"
        f"TARGET_DB_USER={READER_USER}\nTARGET_DB_PASSWORD={reader_pw}\nTARGET_DB_NAME=shop_db\n\n"
        "# Paste a Gemini API key to use a real AI model. Leave empty for the built-in demo mode.\n"
        "GEMINI_API_KEY=\n\n"
        "# Set to 1 when the site is served over HTTPS.\nCOOKIE_SECURE=0\n",
        encoding="utf-8",
    )
    try:
        os.chmod(ENV_PATH, 0o600)
    except OSError:
        pass
    return True


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Create the databases, accounts, .env file and seed data.")
    ap.add_argument("--host", default=os.getenv("DB_HOST", "127.0.0.1"))
    ap.add_argument("--port", type=int, default=int(os.getenv("DB_PORT", "3306")))
    ap.add_argument("--admin-user", default=os.getenv("ADMIN_DB_USER", "root"), help="MySQL account that may create databases and users")
    ap.add_argument("--admin-password", default=os.getenv("ADMIN_DB_PASSWORD"))
    ap.add_argument("--app-admin-user", help="username for the web app's administrator")
    ap.add_argument("--app-admin-email")
    ap.add_argument("--app-admin-password")
    ap.add_argument("--test-db", action="store_true", help="also create app_db_test for running the automated tests")
    ap.add_argument("--reset", action="store_true", help="DROP app_db first (deletes all app data!)")
    ap.add_argument("--yes", action="store_true", help="don't ask for confirmation with --reset")
    a = ap.parse_args(argv)
    interactive = sys.stdin.isatty()

    if a.admin_password is None:
        a.admin_password = getpass.getpass(f"MySQL password for '{a.admin_user}' (empty if none): ") if interactive else ""
    try:
        conn = mysql.connector.connect(host=a.host, port=a.port, user=a.admin_user, password=a.admin_password, autocommit=True)
    except mysql.connector.Error as e:
        print(f"Could not connect to MySQL at {a.host}:{a.port} as '{a.admin_user}': {e}", file=sys.stderr)
        return 1

    if a.reset:
        if not a.yes and (not interactive or input("This DELETES the app database 'app_db'. Type 'yes' to continue: ").strip() != "yes"):
            print("Cancelled.")
            return 1
        conn.cursor().execute("DROP DATABASE IF EXISTS app_db")

    # Reuse passwords from an existing .env so re-running stays consistent; otherwise generate new ones.
    existing = _read_env_file()
    app_pw = existing.get("DB_PASSWORD") or secrets.token_urlsafe(18)
    reader_pw = existing.get("TARGET_DB_PASSWORD") or secrets.token_urlsafe(18)
    pw_map = {PLACEHOLDER_APP_PW: app_pw, PLACEHOLDER_READER_PW: reader_pw}

    have_schema = _scalar(conn, "SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA='app_db' AND TABLE_NAME='users'")
    if have_schema:
        print("app_db already has tables: leaving them as they are (use --reset to start over).")
    else:
        run_sql_file(conn, SQL_DIR / "001_schema.sql")
        print("Created app_db and its tables.")
    run_sql_file(conn, SQL_DIR / "002_evaluation.sql")          # idempotent (IF NOT EXISTS)
    run_sql_file(conn, SQL_DIR / "003_demo_target.sql", pw_map)  # idempotent (IF NOT EXISTS / INSERT IGNORE)
    run_sql_file(conn, SQL_DIR / "004_app_user.sql", pw_map)
    print("Created shop_db (sample data) and the accounts 'llm_reader' (read-only) and 'sqlllm_app'.")

    # CREATE USER IF NOT EXISTS keeps an old password, so force the passwords to match .env.
    cur = conn.cursor()
    for user, pw in ((APP_USER, app_pw), (READER_USER, reader_pw)):
        for host in ("%", "localhost"):
            cur.execute(f"ALTER USER IF EXISTS '{user}'@'{host}' IDENTIFIED BY '{pw}'")

    if a.test_db:
        for name in ("001_schema.sql", "002_evaluation.sql"):
            sql = (SQL_DIR / name).read_text(encoding="utf-8").replace("app_db", "app_db_test")
            if name.startswith("001") and _scalar(conn, "SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA='app_db_test' AND TABLE_NAME='users'"):
                continue
            cur2 = conn.cursor()
            for stmt in split_statements(sql):
                cur2.execute(stmt)
            cur2.close()
        for host in ("%", "localhost"):
            cur.execute(f"GRANT SELECT, INSERT, UPDATE, DELETE ON app_db_test.* TO '{APP_USER}'@'{host}'")
        print("Created app_db_test for the automated tests.")
    cur.execute("FLUSH PRIVILEGES")
    cur.close()
    conn.close()

    if write_env(a.host, a.port, app_pw, reader_pw):
        print(f"Wrote {ENV_PATH.name} with the generated passwords.")
    else:
        print(f"{ENV_PATH.name} already exists: left unchanged (passwords in it were applied to the MySQL accounts).")

    # Seed using the app account; set the environment before importing the backend (it reads it at import).
    os.environ.update({"DB_HOST": a.host, "DB_PORT": str(a.port), "DB_USER": APP_USER, "DB_PASSWORD": app_pw, "DB_NAME": "app_db"})
    from backend import auth, seed
    seed.seed_reference_data()
    print("Seeded plans, the default prompt template, few-shot examples and test questions.")

    if not a.app_admin_user and interactive and input("Create an administrator account for the web app? [Y/n] ").strip().lower() in ("", "y", "yes"):
        a.app_admin_user = input("  Admin username: ").strip()
        a.app_admin_email = input("  Admin email: ").strip()
        a.app_admin_password = getpass.getpass("  Admin password (min 8 characters): ")
    if a.app_admin_user:
        if not (a.app_admin_email and a.app_admin_password):
            print("--app-admin-email and --app-admin-password are required with --app-admin-user", file=sys.stderr)
            return 1
        try:
            seed.create_admin(a.app_admin_user, a.app_admin_email, a.app_admin_password)
            print(f"Created administrator '{a.app_admin_user}'.")
        except auth.AuthError as e:
            print(f"Could not create the administrator: {e}", file=sys.stderr)
            return 1

    print("\nDone. Start the app with:  python run.py   then open http://127.0.0.1:8000")
    return 0


if __name__ == "__main__":
    sys.exit(main())
